// Builds template/bug-to-pr-room.template.yaml from agents/*.md so each role's instructions live in one file.
// Switch fills {params} in names, room and kickoff but NOT in agent instructions (checked in a live run),
// so values used inside instructions are baked here: node scripts/build-template.mjs [--team bug3] [--repo <url>] [--hint "<text>"|none]
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const arg = (k, d) => { const i = process.argv.indexOf(`--${k}`); return i > -1 ? process.argv[i + 1] : d; };
const team = arg('team', 'bug');
const repo = arg('repo', 'https://github.com/Guten-Morgen1302/bug2pr-demo.git');
const pushpr = arg('pushpr', fileURLToPath(new URL('./push-pr.mjs', import.meta.url)).replaceAll(String.fromCharCode(92), '/'));
const edge = arg('edge', fileURLToPath(new URL('../demo-app/edge/compat.mjs', import.meta.url)).replaceAll(String.fromCharCode(92), '/'));
const hintArg = arg('hint', 'Start with the simplest change that fixes the reported input: make the slug regex unicode-aware, with the Unicode property classes for letters and digits. Ship it if the reported input now works.');
// Agents that run the cloned repo's code need Claude Code's permission prompts off (bypass), else its safety check refuses external code. Pass --no-bypass to keep prompts.
const bypass = !process.argv.includes('--no-bypass');
const hint = hintArg === 'none' ? '' : hintArg;
const bake = (s) => s.replaceAll('{team}', team).replaceAll('{repo}', repo).replaceAll('{pushpr}', pushpr).replaceAll('{hint}', hint).replaceAll('{edge}', edge);
const read = (f) => readFileSync(new URL(`../agents/${f}.md`, import.meta.url), 'utf8').trim();
const indent = (s) => s.split('\n').map((l) => (l ? `      ${l}` : l)).join('\n');
const shared = read('_shared');
const roles = [
  ['triager', 'Triager: restates the bug, keeps the constraint card'],
  ['repro', 'Repro: smallest failing script'],
  ['fixer', 'Fixer: the only agent that changes code'],
  ['reviewer', 'Reviewer: skeptical, cites the constraint card'],
];
const agents = roles.map(([r, desc]) => `  - name: "${team}-${r}"
    display_name: "${r}"
    description: "${desc}"
    provider: claude
    location: "{location}"
    directory: "{$agents_dir}/${team}-${r}"
    isolation: isolated
${bypass && r !== 'triager' ? '    auto_approve: true' + String.fromCharCode(10) : ''}    addressing: anyone
    instructions: |
${indent(bake(`${read(r)}\n\n${shared}`))}`).join('\n');

const yaml = `# Generated by scripts/build-template.mjs (team=${team}). Do not edit by hand.
version: 1
params:
  bridge:
    type: bridge
    label: Messaging app (Discord)
    default: [Discord, $first]
  location:
    type: location
    default: local
    input: advanced
agents:
${agents}
room:
  name: "${team}-bug-to-pr"
  description: "Bug to reviewed PR: triager, repro, fixer, reviewer, plus a human gate"
  bridge: "{bridge}"
  agents: ["${team}-triager", "${team}-repro", "${team}-fixer", "${team}-reviewer"]
  users: ["{$creator}"]
kickoff: |
  @${team}-triager the room is ready. Room creator: {$creator}. Humans: post a bug report, then state any constraints. To decide, the creator mentions the reviewer: @${team}-reviewer approve, or @${team}-reviewer reject <reason>, only when the reviewer asks.
`;
writeFileSync(new URL('../template/bug-to-pr-room.template.yaml', import.meta.url), yaml);
console.log(`wrote template/bug-to-pr-room.template.yaml (team=${team})`);
